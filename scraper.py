# Convert complex Python values into SQLite-compatible values.
def sqlite_value(value):

    # Convert lists and dictionaries into JSON text.
    if isinstance(value, (list, dict)):

        # Convert the value into JSON text.
        return json.dumps(value)

    # Return strings, numbers and None unchanged.
    return value


