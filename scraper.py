# Create the LinkedIn scraper.
scraper = LinkedinScraper(

    # Use the default ChromeDriver location.
    chrome_executable_path=None,

    # Use the default Chrome installation.
    chrome_binary_location=None,

    # Use the package's default Chrome options.
    chrome_options=None,

    # Show the browser while scraping.
    headless=False,

    # Use one browser worker.
    max_workers=1,

    # Wait at least 0.8 seconds between jobs.
    slow_mo=0.8,

    # Automatically adjust scraping speed.
    adaptive_slow_mo=True,

    # Allow 40 seconds for page loads.
    page_load_timeout=40,

    # Use the existing LinkedIn Chrome profile.
    user_data_dir=str(LINKEDIN_PROFILE_DIR),

    # Allow interactive login if required.
    interactive_login=True
)

# Close only this scraper's Chrome session on normal or error exit.
atexit.register(scraper.close)


# Register the search-start callback.
scraper.on(
    Events.BEGIN,
    on_begin
)

# Register the job callback.
scraper.on(
    Events.DATA,
    on_data
)

# Register the scraper error callback.
scraper.on(
    Events.ERROR,
    on_error
)




# Store statistics for the current scraping run.
run_stats = {
    'jobs_found': 0,
    'duplicates': 0,
    'english': 0,
    'undetected': 0,
    'final_count': 0,
    'search_times': [],
    'countries': {}
}


# Create counters for every searched country.
for _, country, _ in SEARCHES:

    # Initialise counters for this country.
    run_stats['countries'][country] = {
        'found': 0,
        'valid': 0
    }


# Record when the complete scraping script starts.
SCRIPT_START_TIME = time.perf_counter()


# Run each search sequentially.
for search_number, (search_name, country, search_url) in enumerate(SEARCHES, start=1):

    # Record when this individual search starts.
    search_start_time = time.perf_counter()

    # Reset the current pagination counter.
    CURRENT_PAGE_JOBS = 0

    # Reset the current pagination URL.
    CURRENT_PAGE_URL = None
    CURRENT_SEARCH_JOBS = 0

    # Update the current country.
    CURRENT_COUNTRY = country
    CURRENT_SEARCH_NAME = search_name
    print(f"\nSEARCH {search_number}/{len(SEARCHES)}: {search_name} ({country})")

    # Update the current search URL.
    CURRENT_SEARCH_URL = search_url

    # Create a query using the supplied URL.
    query = Query(
        url=search_url
    )

    # Try to run the LinkedIn search.
    try:

        # Run the LinkedIn search.
        # limit is important!!!!!!!! have it low for testing
        scraper.run(
            query,
            options=QueryOptions(
                limit=200
            )
        )

    # Stop only the current search when pagination is exhausted.
    except EmptyPaginationPage:

        # Print that the search has finished normally.
        print(
            f'[SEARCH COMPLETE] {search_name} '
            f'reached an empty pagination page.'
        )

    # Finish the per-search progress display.
    if CURRENT_SEARCH_TRACKER:
        CURRENT_SEARCH_TRACKER.finish()

    # Calculate how long this search took.
    search_time = (
        time.perf_counter() - search_start_time
    )

    # Store the search duration.
    run_stats['search_times'].append(
        (
            search_name,
            search_time
        )
    )

    # Print a concise search completion message.
    print(f"✓ Search {search_number}/{len(SEARCHES)} completed in {search_time / 60:.2f} min")


# Close the scraper-owned Chrome session after all searches finish.
scraper.close()

# Record the complete scraper runtime for future estimates.
SCRAPER_DURATION = time.perf_counter() - SCRIPT_START_TIME
save_sample("runs", "Scraping", SCRAPER_DURATION)
print(f"✓ Scraping finished in {format_duration(SCRAPER_DURATION)}")

# Generate the final statistics after all searches finish.
print_final_statistics()