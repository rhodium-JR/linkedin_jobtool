# Handle the start of each search.
def on_begin(data: EventBegin):

    # Print the approximate result count.
    global CURRENT_SEARCH_TRACKER
    total = int(data.job_total or 0)
    print(f"LinkedIn reports approximately {total} results.")
    CURRENT_SEARCH_TRACKER = ProgressTracker(
        f"Scraping {CURRENT_SEARCH_NAME}", total, "job"
    )


# Handle each scraped job.
def on_data(data: EventData):

    # Count every job returned by LinkedIn.
    global CURRENT_SEARCH_JOBS
    run_stats['jobs_found'] += 1
    CURRENT_SEARCH_JOBS += 1
    if CURRENT_SEARCH_TRACKER:
        CURRENT_SEARCH_TRACKER.update(
            CURRENT_SEARCH_JOBS,
            (data.title or "Untitled job")[:65]
        )

    # Count the job against its searched country.
    run_stats['countries'][CURRENT_COUNTRY]['found'] += 1

    # Get the job description.
    description = data.description or ''

    # Show whether company and description extraction succeeded.
    company_text = (getattr(data, 'company', None) or '').strip()
    description_words = ' '.join(description.split())
    preview = ' '.join(description_words.split()[:15])
    print(f"Company: {'Yes — ' + company_text if company_text else 'NO'}", flush=True)
    print(
        f"Description: {'Yes — ' + preview if preview else 'NO'}",
        flush=True,
    )

    # Get the LinkedIn job location.
    location = getattr(
        data,
        'place',
        None
    )

    # Convert the location to text when necessary.
    if location is not None:

        # Convert non-string locations into strings.
        location = str(location)

    # Report how much description text was extracted.

    # Set the default language values.
    language = None
    lang_det = 'N'

    # Detect language when enough text is available.
    if len(description.strip()) >= 50:

        # Try to detect the description language.
        try:

            # Detect the description language.
            language = detect(description)

            # Mark English descriptions as valid.
            if language == 'en':

                # Mark the job as English.
                lang_det = 'Y'

                # Count English jobs.
                run_stats['english'] += 1

                # Count valid jobs for this country.
                run_stats['countries'][CURRENT_COUNTRY]['valid'] += 1

        # Handle language detection failures.
        except LangDetectException:

            # Count failed language detection.
            run_stats['undetected'] += 1

    else:

        # Count descriptions that are too short.
        run_stats['undetected'] += 1

    # Print the language detection result.

    # Reject confirmed non-English jobs, but retain undetected jobs.
    if lang_det != 'Y' and language is not None:

        # Print the filtering result.
        print(f"[LANGUAGE SKIP] {data.title} | detected {language}")

        # Stop processing this job.
        return

    # Try to extract the LinkedIn job ID.
    try:

        # Extract the job ID from the LinkedIn URL.
        linkedin_id = (
            data.link
            .split('/jobs/view/')[1]
            .split('/')[0]
        )

    # Handle unexpected LinkedIn URL formats.
    except (IndexError, AttributeError):

        # Store no ID when the URL is unexpected.
        linkedin_id = None

    # Record the current timestamp.
    timestamp = datetime.now().isoformat(
        timespec='seconds'
    )

    # Open the SQLite database.
    connection = sqlite3.connect(DATABASE)

    # Create a database cursor.
    cursor = connection.cursor()

    # Check whether this job already exists.
    cursor.execute(
        '''
        SELECT description_hash
        FROM jobs
        WHERE linkedin_id = ?
        ''',
        (linkedin_id,)
    )

    # Determine whether this is a duplicate.
    previous_row = cursor.fetchone()
    is_duplicate = previous_row is not None
    previous_hash = previous_row[0] if previous_row else None
    description_hash = hashlib.sha256(description.encode("utf-8")).hexdigest() if description else None
    description_changed = bool(previous_hash and description_hash and previous_hash != description_hash)

    # Count duplicate jobs.
    if is_duplicate:

        # Increment the duplicate counter.
        run_stats['duplicates'] += 1

    # Insert the job or update an existing job.
    cursor.execute('''
        INSERT INTO jobs (
            link,
            title,
            company,
            location,
            country,
            date_text,
            linkedin_id,
            company_link,
            insights,
            description,
            language,
            LangDet,
            prompted,
            search_url,
            first_seen,
            last_seen,
            description_hash
        )
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(linkedin_id) DO UPDATE SET
            link = excluded.link,
            title = excluded.title,
            company = excluded.company,
            location = excluded.location,
            country = excluded.country,
            date_text = excluded.date_text,
            company_link = excluded.company_link,
            insights = excluded.insights,
            description = CASE WHEN excluded.description IS NOT NULL AND excluded.description != '' THEN excluded.description ELSE jobs.description END,
            language = excluded.language,
            LangDet = excluded.LangDet,
            search_url = excluded.search_url,
            last_seen = excluded.last_seen,
            description_hash = COALESCE(excluded.description_hash, jobs.description_hash),
            processing_status = CASE WHEN excluded.description_hash IS NOT NULL AND (jobs.description_hash IS NULL OR excluded.description_hash != jobs.description_hash) THEN 'SCRAPED' ELSE jobs.processing_status END,
            rejected = CASE WHEN excluded.description_hash IS NOT NULL AND jobs.description_hash IS NOT NULL AND excluded.description_hash != jobs.description_hash THEN 'N' ELSE jobs.rejected END,
            rejection_point = CASE WHEN excluded.description_hash IS NOT NULL AND jobs.description_hash IS NOT NULL AND excluded.description_hash != jobs.description_hash THEN NULL ELSE jobs.rejection_point END,
            rejection_reason = CASE WHEN excluded.description_hash IS NOT NULL AND jobs.description_hash IS NOT NULL AND excluded.description_hash != jobs.description_hash THEN NULL ELSE jobs.rejection_reason END,
            prompted = CASE WHEN excluded.description_hash IS NOT NULL AND jobs.description_hash IS NOT NULL AND excluded.description_hash != jobs.description_hash THEN 'N' ELSE jobs.prompted END
    ''', (

        # Store the job URL.
        sqlite_value(data.link),

        # Store the job title.
        sqlite_value(data.title),

        # Store the company name.
        sqlite_value(data.company),

        # Store the LinkedIn location.
        sqlite_value(location),

        # Store the searched country.
        sqlite_value(CURRENT_COUNTRY),

        # Store the LinkedIn date text.
        sqlite_value(data.date_text),

        # Store the LinkedIn job ID.
        sqlite_value(linkedin_id),

        # Store the company URL.
        sqlite_value(data.company_link),

        # Store job insights.
        sqlite_value(data.insights),

        # Store the full description.
        sqlite_value(description),

        # Store the detected language.
        sqlite_value(language),

        # Store the English-language flag.
        sqlite_value(lang_det),

        # Keep existing jobs marked as analysed.
        sqlite_value(
            'N'
            if not is_duplicate
            else None
        ),

        # Store the current search URL.
        sqlite_value(CURRENT_SEARCH_URL),

        # Store the first-seen timestamp.
        sqlite_value(timestamp),

        # Store the last-seen timestamp.
        sqlite_value(timestamp),
        sqlite_value(description_hash)
    ))

    # Calculate the current database job count.
    cursor.execute(
        'SELECT COUNT(*) FROM jobs'
    )

    # Store the final database count.
    run_stats['final_count'] = cursor.fetchone()[0]

    # Save the database changes.
    connection.commit()

    # Close the database connection.
    connection.close()

    # Invalidate old screening when the description changed.
    if is_duplicate and not description_changed:
        # Keep the accepted database's last-seen date current.
        update_accepted_job_seen(
            linkedin_id,
            timestamp,
            CURRENT_SEARCH_URL
        )

    if description_changed:
        # Clear obsolete AI screening fields in the master record.
        with sqlite3.connect(DATABASE) as reset_connection:
            reset_connection.execute(
                """UPDATE jobs SET
                   ai_summary = NULL, ai_job_type = NULL,
                   ai_phd_requirement = NULL, ai_subject_area = NULL,
                   ai_seniority = NULL, ai_experience_years = NULL,
                   ai_working_language = NULL, ai_decision = NULL,
                   ai_bin_reason = NULL, ai_reason = NULL,
                   last_processed = NULL, processing_error = NULL
                   WHERE linkedin_id = ?""",
                (linkedin_id,)
            )
        # Remove the outdated accepted and matched record.
        remove_accepted_job(linkedin_id)

    # Print the saved job.
    status = "duplicate updated" if is_duplicate else "new job saved"
    print(f"[SAVED] {data.title} | {data.company or 'Unknown company'} | {linkedin_id} | {status}")


# Handle scraper errors.
def on_error(error):

    # Print the scraper error.
    print(f'[SCRAPER ERROR] {error}')


# Generate the final scraping statistics.
def print_final_statistics():

    todays_date = datetime.now().strftime('%Y-%m-%d')


    # Get the total number of jobs found.
    jobs_found = run_stats['jobs_found']

    # Get the number of duplicates.
    duplicates = run_stats['duplicates']

    # Get the number of English jobs.
    english = run_stats['english']

    # Get the number of undetected languages.
    undetected = run_stats['undetected']

    # Get the final database count.
    final_count = run_stats['final_count']

    # Calculate the duplicate percentage.
    duplicate_percent = round(
        duplicates / jobs_found * 100
    ) if jobs_found else 0

    # Calculate the English percentage.
    english_percent = round(
        english / jobs_found * 100
    ) if jobs_found else 0

    # Calculate the undetected percentage.
    undetected_percent = round(
        undetected / jobs_found * 100
    ) if jobs_found else 0

    # Calculate the final percentage.
    final_percent = round(
        final_count / jobs_found * 100
    ) if jobs_found else 0

    # Calculate the total script runtime.
    total_time = (
        time.perf_counter() - SCRIPT_START_TIME
    )

    # Convert total seconds into minutes.
    total_minutes = int(total_time // 60)

    # Calculate the remaining seconds.
    total_seconds = total_time % 60

    # Create the summary lines.
    lines = [
        '',
        '========================================',
        f'SCRAPING SUMMARY {todays_date}',
        '========================================',
        f'Jobs found          - {jobs_found} (100%)',
        f'Duplicates found    - {duplicates} ({duplicate_percent}%)',
        f'Jobs in English     - {english} ({english_percent}%)',
        f'Language undetected - {undetected} ({undetected_percent}%)',
        f'Final job count     - {final_count} ({final_percent}%)',
        '',
        'SEARCH TIMES',
        '========================================'
    ]

    # Add the duration of every search.
    for search_name, search_time in run_stats['search_times']:

        # Convert search time into minutes.
        minutes = int(search_time // 60)

        # Calculate the remaining seconds.
        seconds = search_time % 60

        # Add the search timing.
        lines.append(
            f'{search_name:<35} - '
            f'{minutes} min {seconds:.2f} sec'
        )

    # Add the total runtime.
    lines.extend([
        '',
        f'TOTAL SCRIPT TIME   - '
        f'{total_minutes} min {total_seconds:.2f} sec',
        '',
        'COUNTRY STATISTICS',
        '========================================'
    ])

    # Add statistics for every country.
    for country, stats in run_stats['countries'].items():

        # Get the number of jobs found.
        found = stats['found']

        # Get the number of valid jobs.
        valid = stats['valid']

        # Calculate the percentage of all jobs.
        found_percent = round(
            found / jobs_found * 100
        ) if jobs_found else 0

        # Calculate the percentage surviving filtering.
        valid_percent = round(
            valid / found * 100
        ) if found else 0

        # Add the country statistics.
        lines.append(
            f'{country:<20} - '
            f'{found} ({found_percent}%), '
            f'valid {valid} ({valid_percent}%)'
        )

    # Add the closing separator.
    lines.append(
        '========================================'
    )

    # Combine all lines into one report.
    summary = '\n'.join(lines)

    # Print the complete report.
    print(summary)

    # Overwrite the previous log file.
    with open(
        LOG_FILE,
        'w',
        encoding='utf-8'
    ) as logfile:

        # Write the complete report.
        logfile.write(summary)


