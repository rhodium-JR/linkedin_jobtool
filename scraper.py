# Define the exception used to stop an exhausted search.
class EmptyPaginationPage(Exception):

    # Stop the current scraper run after an empty page.
    pass


# Monitor the LinkedIn scraper's pagination messages.
class PaginationMonitor(logging.Handler):

    # Handle every message generated by the scraper.
    def emit(self, record):

        # Access the global current-page counter.
        global CURRENT_PAGE_JOBS

        # Access the global current-page URL.
        global CURRENT_PAGE_URL

        # Convert the log record into text.
        message = record.getMessage()

        # Detect the beginning of a pagination page.
        if 'Opening ' in message:

            # Extract the URL from the log message.
            match = re.search(
                r'Opening (https?://\S+)',
                message
            )

            # Store the current pagination URL.
            if match:

                # Save the URL being opened.
                CURRENT_PAGE_URL = match.group(1)

            # Reset the number of jobs on this page.
            CURRENT_PAGE_JOBS = 0

            # Do not process this message further.
            return

        # Detect a successfully processed LinkedIn job.
        if 'Processed' in message:

            # Count the job on the current page.
            CURRENT_PAGE_JOBS += 1

            # Do not process this message further.
            return

        # Detect the end of a pagination page.
        if 'No more jobs to process in this page' in message:

            # Check whether the page contained no jobs.
            if CURRENT_PAGE_JOBS == 0:

                # Print the stopping information.
                print(
                    '\n[EMPTY PAGE] '
                    'No jobs found on pagination page.'
                )

                # Print the URL that was empty.
                if CURRENT_PAGE_URL:

                    # Show the empty pagination URL.
                    print(
                        f'[EMPTY PAGE] {CURRENT_PAGE_URL}'
                    )

                # Stop the current scraper.run() call.
                raise EmptyPaginationPage()


